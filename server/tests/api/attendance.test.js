// Attendance integrity: check-in rules, duplicate prevention (including
// simultaneous requests), closed sessions and server-generated timestamps.
import request from 'supertest';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { disconnectDatabase, prisma } from '../../src/db/client.js';
import { createFixtures, login, makeApp, openSessionInDb, resetDatabase } from '../helpers.js';

let app;
let fx;
let session; // lecturer1's open CIT2004 session (s1 enrolled, s2 not)

beforeAll(() => {
  app = makeApp();
});
beforeEach(async () => {
  await resetDatabase();
  fx = await createFixtures();
  session = await openSessionInDb(fx.users.lecturer1, fx.modules.CIT2004, fx.semesters.current);
});
afterAll(disconnectDatabase);

const checkIn = (body) => request(app).post('/api/attendance').send(body);

describe('POST /api/attendance', () => {
  it('records attendance with a server-generated timestamp', async () => {
    const before = Date.now();
    const res = await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id });
    expect(res.status).toBe(201);
    expect(res.body.data.course).toEqual({ code: 'CIT2004', name: 'Object Oriented Programming' });

    const record = await prisma.attendance.findFirst({ where: { sessionId: session.id } });
    expect(record.studentId).toBe(fx.students.s1.id);
    // Generated by PostgreSQL now(): within a few seconds of the request.
    expect(Math.abs(record.checkedInAt.getTime() - before)).toBeLessThan(5000);
  });

  it('rejects a second check-in to the same session with 409', async () => {
    await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id });
    const res = await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id });
    expect(res.status).toBe(409);
    expect(res.body).toEqual({
      success: false,
      message: 'Attendance has already been recorded for this session.',
      code: 'ALREADY_CHECKED_IN',
    });
    expect(await prisma.attendance.count()).toBe(1);
  });

  it('creates exactly one record when many identical requests arrive at once', async () => {
    const body = { idNumber: fx.students.s1.idNumber, sessionId: session.id };
    const responses = await Promise.all(Array.from({ length: 12 }, () => checkIn(body)));
    const statuses = responses.map((r) => r.status);
    expect(statuses.filter((s) => s === 201)).toHaveLength(1);
    expect(statuses.filter((s) => s === 409)).toHaveLength(11);
    expect(await prisma.attendance.count({ where: { sessionId: session.id } })).toBe(1);
  });

  it('rejects check-in to a course the student is not enrolled in', async () => {
    const res = await checkIn({ idNumber: fx.students.s2.idNumber, sessionId: session.id });
    expect(res.status).toBe(403);
    expect(res.body.code).toBe('NOT_ENROLLED');
  });

  it('only counts enrollments for the session semester', async () => {
    await prisma.enrollment.create({
      data: { studentId: fx.students.s2.id, moduleId: fx.modules.CIT2004.id, semesterId: fx.semesters.next.id },
    });
    const res = await checkIn({ idNumber: fx.students.s2.idNumber, sessionId: session.id });
    expect(res.status).toBe(403);
  });

  it('rejects check-in when the session is closed', async () => {
    await prisma.classSession.update({ where: { id: session.id }, data: { closedAt: new Date() } });
    const res = await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id });
    expect(res.status).toBe(409);
    expect(res.body.code).toBe('SESSION_CLOSED');
  });

  it('rejects check-in after the lecturer closes the session through the API', async () => {
    const { agent, csrf } = await login(app, 'lecturer', 'LEC001');
    const closeRes = await agent.patch(`/api/class-sessions/${session.id}/close`).set("X-CSRF-Token", csrf);
    expect(closeRes.status, JSON.stringify(closeRes.body)).toBe(200);
    const res = await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id });
    expect(res.status).toBe(409);
  });

  it('returns 404 for unknown sessions and unknown students', async () => {
    expect((await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: 999999 })).body.code).toBe('SESSION_NOT_FOUND');
    expect((await checkIn({ idNumber: '7777777', sessionId: session.id })).body.code).toBe('STUDENT_NOT_FOUND');
  });

  it('rejects a client-supplied timestamp instead of trusting it', async () => {
    const res = await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: session.id, checkedInAt: '2001-01-01T00:00:00Z' });
    expect(res.status).toBe(400);
    expect(await prisma.attendance.count()).toBe(0);
  });

  it('validates the request body', async () => {
    expect((await checkIn({ idNumber: fx.students.s1.idNumber })).status).toBe(400);
    expect((await checkIn({ idNumber: fx.students.s1.idNumber, sessionId: 'abc' })).status).toBe(400);
  });
});

describe('database-level duplicate prevention', () => {
  it('has the UNIQUE (session_id, student_id) constraint on attendance', async () => {
    const rows = await prisma.$queryRaw`
      SELECT conname, pg_get_constraintdef(oid) AS definition
      FROM pg_constraint
      WHERE conrelid = 'attendance'::regclass AND contype = 'u'`;
    expect(rows).toEqual([{ conname: 'unique_session_student', definition: 'UNIQUE (session_id, student_id)' }]);
  });

  it('blocks a duplicate even when inserted directly, bypassing the API', async () => {
    await prisma.attendance.create({ data: { sessionId: session.id, studentId: fx.students.s1.id } });
    await expect(prisma.attendance.create({ data: { sessionId: session.id, studentId: fx.students.s1.id } })).rejects.toMatchObject({
      code: 'P2002',
    });
  });

  it('allows only one open session per lecturer, module and semester', async () => {
    await expect(openSessionInDb(fx.users.lecturer1, fx.modules.CIT2004, fx.semesters.current)).rejects.toMatchObject({
      code: 'P2002',
    });
  });
});
