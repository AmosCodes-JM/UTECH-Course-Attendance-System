// Small wrapper around the browser's Fetch API.
//
// - Sends cookies (credentials: 'include') so lecturer/admin sessions work.
// - Adds the CSRF token to every state-changing request.
// - Turns error responses into ApiError objects with the server's message.
// - Notifies the AuthContext when a protected request comes back 401, so the
//   app can send the user to the login page ("your session expired").

const API_URL = (import.meta.env.VITE_API_URL || '/api').replace(/\/$/, '');

let csrfToken = null;
let unauthorizedHandler = null;

export function setCsrfToken(token) {
  csrfToken = token;
}

export function onUnauthorized(handler) {
  unauthorizedHandler = handler;
}

export class ApiError extends Error {
  constructor(status, message, code, errors) {
    super(message);
    this.name = 'ApiError';
    this.status = status;
    this.code = code;
    this.errors = errors ?? [];
  }

  /** Field-level validation messages, e.g. { email: 'Enter a valid email address' }. */
  get fieldErrors() {
    return Object.fromEntries(this.errors.filter((e) => e.field).map((e) => [e.field, e.message]));
  }
}

function buildUrl(path, query) {
  const url = `${API_URL}${path}`;
  if (!query) return url;
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    if (value !== undefined && value !== null && value !== '') params.set(key, value);
  }
  const qs = params.toString();
  return qs ? `${url}?${qs}` : url;
}

async function send(path, { method = 'GET', body, query, signal } = {}) {
  const headers = { Accept: 'application/json' };
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  if (method !== 'GET' && csrfToken) headers['X-CSRF-Token'] = csrfToken;

  let response;
  try {
    response = await fetch(buildUrl(path, query), {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
      credentials: 'include',
      signal,
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    throw new ApiError(0, 'Cannot reach the server. Check your connection and try again.', 'NETWORK_ERROR');
  }
  return response;
}

async function toError(response) {
  let payload = {};
  try {
    payload = await response.json();
  } catch {
    // Non-JSON error (e.g. a proxy error page).
  }
  const error = new ApiError(
    response.status,
    payload.message || `The server returned an error (${response.status}).`,
    payload.code,
    payload.errors,
  );
  if (response.status === 401 && unauthorizedHandler && ['UNAUTHENTICATED', 'SESSION_INVALID'].includes(error.code)) {
    unauthorizedHandler(error);
  }
  return error;
}

/** JSON request. Resolves with the response's `data`; rejects with ApiError. */
export async function apiRequest(path, options) {
  const response = await send(path, options);
  if (!response.ok) throw await toError(response);
  const payload = await response.json();
  return payload.data;
}

export const api = {
  get: (path, query, options) => apiRequest(path, { ...options, query }),
  post: (path, body) => apiRequest(path, { method: 'POST', body: body ?? {} }),
  patch: (path, body) => apiRequest(path, { method: 'PATCH', body: body ?? {} }),
  delete: (path) => apiRequest(path, { method: 'DELETE' }),
};

/** Download a file (Excel/PDF export) generated by the server. */
export async function downloadFile(path, query, fallbackName) {
  const response = await send(path, { query });
  if (!response.ok) throw await toError(response);
  const blob = await response.blob();
  const disposition = response.headers.get('Content-Disposition') || '';
  const match = disposition.match(/filename="?([^"]+)"?/);
  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.download = match ? match[1] : fallbackName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(link.href), 1000);
}
